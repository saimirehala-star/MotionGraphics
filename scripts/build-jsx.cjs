const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
const source = read('extension/host/main.jsx');
const marker = 'var MG2023Host = (function () {';
const start = source.indexOf(marker);
if (start < 0) throw new Error('Could not locate the shared host engine.');
const engine = source.slice(start);
if (/\$\.evalFile|#include/.test(engine)) throw new Error('Standalone engine must not load other files.');
const browserSource = name => read(name).replace(/^if \(typeof module !== 'undefined' && module\.exports\) \{ module\.exports = \w+; \}\n?/gm, '');
const sections = [
  ['JSON compatibility (Public Domain)', read('extension/vendor/json2.js')],
  ['Reference preset data', browserSource('extension/js/reference-presets.js')],
  ['Shared preset catalog', browserSource('extension/js/catalog.js')],
  ['Shared motion math', browserSource('extension/js/motion.js')],
  ['Shared AE engine', engine],
  ['Native ScriptUI panel', read('scriptui/panel.jsx')]
];
const api = `
return {
    version: '1.8.0', catalog: MGCatalog, host: MG2023Host, watch: MGScriptUI.watch,
    create: function (container, runner) {
        if (!runner) {
            runner = function (request) {
                var comp = app.project ? app.project.activeItem : null;
                if (!(comp instanceof CompItem)) { comp = null; }
                return MG2023Host.run(request, comp);
            };
        }
        return MGScriptUI.create(container, runner);
    }
};`;
const contents = '#target aftereffects\n' +
  '// Motion Graphics JSX 1.8.0 | AE 2023 | Standalone; no CEP or external files.\n' +
  '// Generated by scripts/build-jsx.cjs. Edit the shared sources, then rebuild.\n' +
  'var MotionGraphicsJSX = (function () {\nvar JSON;\n' +
  sections.map(([name, text]) => `\n/* === ${name} === */\n${text}`).join('\n') +
  '\n' + api + '\n}());\n\n' + read('scriptui/launch.jsx');
new vm.Script(contents.replace(/^#target.*$/m, ''), { filename: 'MotionGraphics.jsx' });
const directory = path.join(root, 'dist', 'jsx');
fs.mkdirSync(directory, { recursive: true });
const target = path.join(directory, 'MotionGraphics.jsx');
// UTF-8 BOM makes Chinese labels reliable in AE's direct Run Script File loader.
fs.writeFileSync(target, '\uFEFF' + contents, 'utf8');
fs.copyFileSync(path.join(root, 'scriptui', 'README.md'), path.join(directory, 'README.md'));
console.log(`Standalone JSX: ${target} (${fs.statSync(target).size.toLocaleString()} bytes)`);
